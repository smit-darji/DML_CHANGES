create or replace view VW_BACKLOG_HEALTH(
	PROJECT_KEY,
	PROJECT_NAME,
	SPRINT_ID,
	SPRINT_NAME,
	SPRINT_START_DATE,
	SPRINT_COMPLETED_DATE,
	READY_FOR_WORK_POINTS,
	FUTURE_SPRINTS,
	BACKLOG_HEALTH,
	CREATED_DATE,
	UPDATED_DATE
) as 
WITH BASE_METRICS AS (
    SELECT DISTINCT
        SM.PROJECT_KEY AS PROJECT_KEY,
        SM.SPRINT_ID AS SPRINT_ID,
        SUM(CASE WHEN IM.ISSUE_STATUS = 'Done' THEN IM.COMPLETED_POINTS ELSE 0 END) OVER(PARTITION BY SM.SPRINT_ID, SM.PROJECT_KEY) AS TOTAL_POINTS
    FROM ${envId}_CZ.AGILE_REPORTING_MAIN.SPRINT_METRICS SM
    LEFT JOIN ${envId}_CZ.AGILE_REPORTING_MAIN.ISSUE_METRICS IM ON IM.SPRINT_ID = SM.SPRINT_ID AND IM.PROJECT_KEY = SM.PROJECT_KEY
    WHERE IM.BOARD_TYPE = 'Sprints'
),
AVG_LAST_3_SPRINT_POINTS AS (
    SELECT
        PROJECT_KEY,
        SPRINT_ID,
        ZEROIFNULL(ROUND(AVG(TOTAL_POINTS) OVER (PARTITION BY PROJECT_KEY ORDER BY SPRINT_ID ROWS BETWEEN 3 PRECEDING AND 1 PRECEDING), 2)) AS AVG_LAST_3_SPRINT_POINTS
    FROM BASE_METRICS
)
SELECT
    BHM.PROJECT_KEY,
    BHM.PROJECT_NAME,
    BHM.SPRINT_ID,
    BHM.SPRINT_NAME,
    BHM.SPRINT_START_DATE,
    BHM.SPRINT_COMPLETED_DATE,
    BHM.READY_FOR_WORK_POINTS,
    BHM.FUTURE_SPRINTS,
    ROUND(((BHM.READY_FOR_WORK_POINTS/NULLIFZERO(ALSP.AVG_LAST_3_SPRINT_POINTS))/BHM.FUTURE_SPRINTS)*100,1) AS BACKLOG_HEALTH,
    TO_TIMESTAMP_NTZ(CURRENT_TIMESTAMP()) AS CREATED_DATE,
    TO_TIMESTAMP_NTZ(CURRENT_TIMESTAMP()) AS UPDATED_DATE
FROM ${envId}_CZ.AGILE_REPORTING_MAIN.BACKLOG_HEALTH_METRICS BHM
LEFT JOIN AVG_LAST_3_SPRINT_POINTS ALSP ON BHM.SPRINT_ID = ALSP.SPRINT_ID AND BHM.PROJECT_KEY = ALSP.PROJECT_KEY
;


create or replace view VW_KANBAN(
	PROJECT_KEY,
	PROJECT_NAME,
	WEEK,
	YEAR,
	FIRST_DAY_OF_WEEK,
	TOTAL_LEAD_TIME,
	AVG_BACKLOG_CYCLE_TIME,
	AVG_KANBAN_CYCLE_TIME,
	TIME_IN_OPEN,
	TIME_IN_WORKING,
	TIME_IN_QA,
	THROUGHPUT,
	CREATED_DATE,
	UPDATED_DATE
) as
select
    project_key,
    project_name,
    week,
    year,
    first_day_of_week,
    round(sum(total_lead_time),2) as total_lead_time,
    round(avg(total_open_to_working_time),2) as avg_backlog_cycle_time,
    round(avg(total_working_to_done_time),2) as avg_kanban_cycle_time,
    round(avg(open_status_time),2) as time_in_open,
    round(avg(working_status_time),2) as time_in_working,
    round(avg(qa_status_time),2) as time_in_qa,
    sum(case when issue_status = 'Done' then 1 else 0 end) as throughput,
	TO_TIMESTAMP_NTZ(CURRENT_TIMESTAMP()) AS CREATED_DATE,
	TO_TIMESTAMP_NTZ(CURRENT_TIMESTAMP()) AS UPDATED_DATE
from ${envId}_CZ.agile_reporting_main.kanban_metrics
group by all
;


