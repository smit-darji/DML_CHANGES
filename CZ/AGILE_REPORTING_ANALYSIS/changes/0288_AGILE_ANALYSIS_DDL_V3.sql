create or replace view VW_SPRINT_TARGET_AND_CHURN(
	PROJECT_KEY,
	PROJECT_NAME,
	SPRINT_ID,
	SPRINT_NAME,
	PLANNED_POINTS,
	COMPLETED_POINTS,
	COMPLETED_RATIO,
	POINTS_ADDED,
	TICKETS_ADDED,
	POINTS_REMOVED,
	TICKETS_REMOVED,
	GROSS_POINT_CHURN,
	GROSS_TICKET_CHURN,
	NET_POINT_CHURN,
	NET_TICKET_CHURN,
	GROSS_POINT_CHURN_RATIO,
	NET_POINT_CHURN_RATIO,
	PLANNING_ACCURACY,
	CREATED_DATE,
	UPDATED_DATE
) as
WITH TOTAL_POINTS AS (
    SELECT DISTINCT
        IM.PROJECT_KEY AS PROJECT_KEY,
        IM.PROJECT_NAME AS PROJECT_NAME,
        IM.SPRINT_ID AS SPRINT_ID,
        IM.SPRINT_NAME AS SPRINT_NAME,
        SUM(IM.PLANNED_POINTS) OVER(PARTITION BY IM.SPRINT_ID, IM.PROJECT_KEY) AS TOTAL_POINTS,
        SUM(IM.COMPLETED_POINTS) OVER(PARTITION BY IM.SPRINT_ID, IM.PROJECT_KEY) AS COMPLETED_POINTS
    FROM ${envId}_CZ.AGILE_REPORTING_MAIN.ISSUE_METRICS IM
    WHERE IM.BOARD_TYPE = 'Sprints'
),
AVG_LAST_3_SPRINT_POINTS AS (
    SELECT DISTINCT
        PROJECT_KEY,
        PROJECT_NAME,
        SPRINT_ID,
        SPRINT_NAME,
        TOTAL_POINTS,
        COMPLETED_POINTS,
        ZEROIFNULL(ROUND(AVG(COMPLETED_POINTS) OVER (PARTITION BY PROJECT_KEY ORDER BY SPRINT_ID ROWS BETWEEN 3 PRECEDING AND 1 PRECEDING), 2)) AS AVG_LAST_3_SPRINT_POINTS
    FROM TOTAL_POINTS
)
SELECT DISTINCT
    IM.PROJECT_KEY,
    IM.PROJECT_NAME,
    IM.SPRINT_ID,
    IM.SPRINT_NAME,
    SP.TOTAL_POINTS AS PLANNED_POINTS,
    SP.COMPLETED_POINTS,
    ZEROIFNULL(SP.COMPLETED_POINTS/NULLIFZERO(SP.TOTAL_POINTS))::NUMBER(38,2) AS COMPLETED_RATIO,
    SM.POINTS_ADDED,
    SM.TICKETS_ADDED,
    SM.POINTS_REMOVED,
    SM.TICKETS_REMOVED,
    SM.GROSS_POINT_CHURN,
    SM.GROSS_TICKET_CHURN,
    SM.NET_POINT_CHURN,
    SM.NET_TICKET_CHURN,
    ZEROIFNULL(SM.GROSS_POINT_CHURN/NULLIFZERO(SP.TOTAL_POINTS))::NUMBER(38,2) AS GROSS_POINT_CHURN_RATIO,
    ZEROIFNULL(SM.NET_POINT_CHURN/NULLIFZERO(SP.TOTAL_POINTS))::NUMBER(38,2) AS NET_POINT_CHURN_RATIO,
    ZEROIFNULL(SP.TOTAL_POINTS/NULLIFZERO(AVG_LAST_3_SPRINT_POINTS))::NUMBER(38,2) AS PLANNING_ACCURACY,
    TO_TIMESTAMP_NTZ(CURRENT_TIMESTAMP()) AS CREATED_DATE,
    TO_TIMESTAMP_NTZ(CURRENT_TIMESTAMP()) AS UPDATED_DATE
FROM ${envId}_CZ.AGILE_REPORTING_MAIN.SPRINT_METRICS SM
LEFT JOIN ${envId}_CZ.AGILE_REPORTING_MAIN.ISSUE_METRICS IM ON IM.SPRINT_ID = SM.SPRINT_ID AND IM.PROJECT_KEY = SM.PROJECT_KEY
LEFT JOIN AVG_LAST_3_SPRINT_POINTS SP ON SM.SPRINT_ID = SP.SPRINT_ID AND SM.PROJECT_KEY = SP.PROJECT_KEY
WHERE IM.BOARD_TYPE = 'Sprints'
;


create or replace view VW_SPRINT_VELOCITY(
	PROJECT_KEY,
	PROJECT_NAME,
	SPRINT_ID,
	SPRINT_NARRATIVE,
	EXECUTIVE_SUMMARY,
	SPRINT_NAME,
	TOTAL_POINTS,
	TOTAL_TICKETS,
	AVG_TICKET_SIZE,
	TOTAL_STORY_POINTS,
	TOTAL_STORY_TICKETS,
	AVG_STORY_SIZE,
	TOTAL_BUG_POINTS,
	TOTAL_BUG_TICKETS,
	AVG_BUG_SIZE,
	TOTAL_TASK_POINTS,
	TOTAL_TASK_TICKETS,
	AVG_TASK_SIZE,
	TOTAL_SPIKE_POINTS,
	TOTAL_SPIKE_TICKETS,
	AVG_SPIKE_SIZE,
	AVG_LAST_3_SPRINT_POINTS,
    CARRY_OVER_TICKET,
    CARRY_OVER_POINTS,
	CREATED_DATE,
	UPDATED_DATE
) as
WITH BASE_METRICS AS (
    SELECT DISTINCT
        SM.PROJECT_KEY AS PROJECT_KEY,
        SM.PROJECT_NAME AS PROJECT_NAME,
        SM.SPRINT_ID AS SPRINT_ID,
        IM.SPRINT_NARRATIVE AS SPRINT_NARRATIVE,
        IM.EXECUTIVE_SUMMARY AS EXECUTIVE_SUMMARY,
        SM.SPRINT_NAME AS SPRINT_NAME,
        
        SUM(CASE WHEN IM.ISSUE_STATUS = 'Done' THEN IM.COMPLETED_POINTS ELSE 0 END) OVER(PARTITION BY SM.SPRINT_ID, SM.PROJECT_KEY) AS TOTAL_POINTS,
        SM.TOTAL_TICKETS AS TOTAL_TICKETS,
        ZEROIFNULL(TOTAL_POINTS/NULLIFZERO(SM.TOTAL_TICKETS))::NUMBER(38,2) AS AVG_TICKET_SIZE,
        
        SUM(CASE WHEN IM.ISSUE_TYPE = 'Story' AND IM.ISSUE_STATUS = 'Done' THEN IM.COMPLETED_POINTS ELSE 0 END) OVER(PARTITION BY SM.SPRINT_ID, SM.PROJECT_KEY) AS TOTAL_STORY_POINTS,
        SM.TOTAL_STORY_TICKETS AS TOTAL_STORY_TICKETS,
        ZEROIFNULL(TOTAL_STORY_POINTS/NULLIFZERO(SM.TOTAL_STORY_TICKETS))::NUMBER(38,2) AS AVG_STORY_SIZE,
        
        SUM(CASE WHEN IM.ISSUE_TYPE = 'Bug' AND IM.ISSUE_STATUS = 'Done' THEN IM.COMPLETED_POINTS ELSE 0 END) OVER(PARTITION BY SM.SPRINT_ID, SM.PROJECT_KEY) AS TOTAL_BUG_POINTS,
        SM.TOTAL_BUG_TICKETS AS TOTAL_BUG_TICKETS,
        ZEROIFNULL(TOTAL_BUG_POINTS/NULLIFZERO(SM.TOTAL_BUG_TICKETS))::NUMBER(38,2) AS AVG_BUG_SIZE,
    
        SUM(CASE WHEN IM.ISSUE_TYPE = 'Task' AND IM.ISSUE_STATUS = 'Done' THEN IM.COMPLETED_POINTS ELSE 0 END) OVER(PARTITION BY SM.SPRINT_ID, SM.PROJECT_KEY) AS TOTAL_TASK_POINTS,
        SM.TOTAL_TASK_TICKETS AS TOTAL_TASK_TICKETS,
        ZEROIFNULL(TOTAL_TASK_POINTS/NULLIFZERO(SM.TOTAL_TASK_TICKETS))::NUMBER(38,2) AS AVG_TASK_SIZE,
        
        SUM(CASE WHEN IM.ISSUE_TYPE = 'Spike' AND IM.ISSUE_STATUS = 'Done' THEN IM.COMPLETED_POINTS ELSE 0 END) OVER(PARTITION BY SM.SPRINT_ID, SM.PROJECT_KEY) AS TOTAL_SPIKE_POINTS,
        SM.TOTAL_SPIKE_TICKETS AS TOTAL_SPIKE_TICKETS,
        ZEROIFNULL(TOTAL_SPIKE_POINTS/NULLIFZERO(SM.TOTAL_SPIKE_TICKETS))::NUMBER(38,2) AS AVG_SPIKE_SIZE,

        SUM(CASE WHEN IM.IS_CARRY_OVER THEN 1 ELSE 0 END) OVER(PARTITION BY SM.SPRINT_ID, SM.PROJECT_KEY) AS CARRY_OVER_TICKET,
        SUM(CASE WHEN IM.IS_CARRY_OVER THEN IM.STORY_POINTS ELSE 0 END) OVER(PARTITION BY SM.SPRINT_ID, SM.PROJECT_KEY) AS CARRY_OVER_POINTS
        
    FROM ${envId}_CZ.AGILE_REPORTING_MAIN.SPRINT_METRICS SM
    LEFT JOIN ${envId}_CZ.AGILE_REPORTING_MAIN.ISSUE_METRICS IM ON IM.SPRINT_ID = SM.SPRINT_ID AND SM.PROJECT_KEY = IM.PROJECT_KEY
    WHERE IM.BOARD_TYPE = 'Sprints'
)
SELECT
    PROJECT_KEY,
    PROJECT_NAME,
    SPRINT_ID,
    SPRINT_NARRATIVE,
    EXECUTIVE_SUMMARY,
    SPRINT_NAME,
    TOTAL_POINTS,
    TOTAL_TICKETS,
    AVG_TICKET_SIZE,
    TOTAL_STORY_POINTS,
    TOTAL_STORY_TICKETS,
    AVG_STORY_SIZE,
    TOTAL_BUG_POINTS,
    TOTAL_BUG_TICKETS,
    AVG_BUG_SIZE,
    TOTAL_TASK_POINTS,
    TOTAL_TASK_TICKETS,
    AVG_TASK_SIZE,
    TOTAL_SPIKE_POINTS,
    TOTAL_SPIKE_TICKETS,
    AVG_SPIKE_SIZE,
    ZEROIFNULL(ROUND(AVG(TOTAL_POINTS) OVER (PARTITION BY PROJECT_KEY ORDER BY SPRINT_ID ROWS BETWEEN 3 PRECEDING AND 1 PRECEDING), 2)) AS AVG_LAST_3_SPRINT_POINTS,
    CARRY_OVER_TICKET,
    CARRY_OVER_POINTS,
    TO_TIMESTAMP_NTZ(CURRENT_TIMESTAMP()) AS CREATED_DATE,
    TO_TIMESTAMP_NTZ(CURRENT_TIMESTAMP()) AS UPDATED_DATE
FROM BASE_METRICS
;


